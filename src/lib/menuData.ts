import type { Category, FoodItem, NutritionalFacts } from '../types';
import type { WeekdayKey } from './dates';

function nf(partial: Partial<NutritionalFacts> & Pick<NutritionalFacts, 'calories' | 'proteinG'>): NutritionalFacts {
  return {
    servingSize: partial.servingSize ?? '1 portion (estimated)',
    calories: partial.calories,
    totalFatG: partial.totalFatG ?? 12,
    saturatedFatG: partial.saturatedFatG ?? 4,
    cholesterolMg: partial.cholesterolMg ?? 45,
    sodiumMg: partial.sodiumMg ?? 420,
    totalCarbG: partial.totalCarbG ?? 28,
    dietaryFiberG: partial.dietaryFiberG ?? 3,
    totalSugarsG: partial.totalSugarsG ?? 4,
    proteinG: partial.proteinG,
  };
}

function img(seed: string): string {
  const q = encodeURIComponent(seed);
  return `https://picsum.photos/seed/${q}/800/600`;
}

interface Seed {
  name: string;
  price: number;
  unitLabel: string;
  qty: number;
  description: string;
  ingredients: string[];
  nutrition: NutritionalFacts;
}

function item(
  weekday: WeekdayKey,
  category: Category,
  index: number,
  seed: Seed,
): FoodItem {
  const id = `${weekday}-${category}-${index}`;
  return {
    id,
    category,
    name: seed.name,
    price: seed.price,
    unitLabel: seed.unitLabel,
    quantityAvailable: seed.qty,
    imageUrl: img(id),
    description: seed.description,
    ingredients: seed.ingredients,
    nutrition: seed.nutrition,
  };
}

