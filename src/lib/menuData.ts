export const WEEKDAY_MENU: Record<WeekdayKey, FoodItem[]> = (Object.keys(PROTEIN_ROTATIONS) as WeekdayKey[]).reduce(
  (acc, day) => {
    const proteins = PROTEIN_ROTATIONS[day].map((s, i) => item(day, 'protein', i, s));
    const veg = VEG_ROTATIONS[day].map((s, i) => item(day, 'vegetarian', i, s));
    const sides = SIDES_ROTATIONS[day].map((s, i) => item(day, 'sides', i, s));
    acc[day] = [...proteins, ...veg, ...sides];
    return acc;
  },
  {} as Record<WeekdayKey, FoodItem[]>,
);

export function getMenuForWeekday(day: WeekdayKey): FoodItem[] {
  return WEEKDAY_MENU[day];
}

export function getItemById(id: string): FoodItem | undefined {
  const menu = WEEKDAY_MENU[id.split('-')[0] as WeekdayKey];
  return menu?.find((m) => m.id === id);
}
